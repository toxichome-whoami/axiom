const std = @import("std");
const builtin = @import("builtin");

pub extern "c" fn __p___argc() callconv(.c) *c_int;
pub extern "c" fn __p___argv() callconv(.c) *[*]?[*:0]u8;
pub extern "c" fn system(cmd: [*:0]const u8) callconv(.c) c_int;

// Windows API
pub extern "kernel32" fn GetCurrentDirectoryA(nBufferLength: u32, lpBuffer: [*:0]u8) callconv(.c) u32;
pub extern "kernel32" fn GetEnvironmentVariableA(lpName: [*:0]const u8, lpBuffer: [*:0]u8, nSize: u32) callconv(.c) u32;
pub extern "kernel32" fn SetEnvironmentVariableA(lpName: [*:0]const u8, lpValue: [*:0]const u8) callconv(.c) i32;
pub extern "kernel32" fn CopyFileA(lpExisting: [*:0]const u8, lpNew: [*:0]const u8, bFailIfExists: i32) callconv(.c) i32;
pub extern "kernel32" fn CreateDirectoryA(lpPathName: [*:0]const u8, lpSecurityAttributes: ?*anyopaque) callconv(.c) i32;
pub extern "kernel32" fn GetFileAttributesA(lpFileName: [*:0]const u8) callconv(.c) u32;
pub extern "kernel32" fn CreateFileA(
    lpFileName: [*:0]const u8,
    dwDesiredAccess: u32,
    dwShareMode: u32,
    lpSecurityAttributes: ?*anyopaque,
    dwCreationDisposition: u32,
    dwFlagsAndAttributes: u32,
    hTemplateFile: ?*anyopaque,
) callconv(.c) ?*anyopaque;
pub extern "kernel32" fn WriteFile(
    hFile: ?*anyopaque,
    lpBuffer: [*]const u8,
    nNumberOfBytesToWrite: u32,
    lpNumberOfBytesWritten: ?*u32,
    lpOverlapped: ?*anyopaque,
) callconv(.c) i32;
pub extern "kernel32" fn CloseHandle(hObject: ?*anyopaque) callconv(.c) i32;

fn ensure_dir(path: [*:0]const u8) void {
    if (builtin.os.tag == .windows) {
        _ = CreateDirectoryA(path, null);
    }
}

fn file_exists(path: [*:0]const u8) bool {
    if (builtin.os.tag == .windows) {
        const attr = GetFileAttributesA(path);
        return attr != 0xFFFFFFFF;
    }
    return false;
}

fn ensure_setup() void {
    ensure_dir(".tools");
    ensure_dir(".tools/bin");
    ensure_dir(".cargo");

    const exe_ext = if (builtin.os.tag == .windows) ".exe" else "";

    std.debug.print("==> Compiling native Zig toolchain shims in Zig...\n", .{});
    const compile_shim = "zig build-exe -O ReleaseFast -lc \"-femit-bin=.tools/bin/gcc" ++ exe_ext ++ "\" tools/zig/toolchain_shim.zig";
    if (system(compile_shim) != 0) {
        std.debug.print("Error: Failed to compile toolchain_shim.zig using zig\n", .{});
        std.process.exit(1);
    }

    const tools = [_][*:0]const u8{
        ".tools/bin/g++" ++ exe_ext,
        ".tools/bin/ar" ++ exe_ext,
        ".tools/bin/dlltool" ++ exe_ext,
        ".tools/bin/clang" ++ exe_ext,
        ".tools/bin/clang++" ++ exe_ext,
    };

    for (tools) |dest| {
        if (builtin.os.tag == .windows) {
            _ = CopyFileA(".tools/bin/gcc.exe", dest, 0);
        }
    }

    if (builtin.os.tag == .windows) {
        const compile_cp = "zig build-exe -O ReleaseFast \"-femit-bin=.tools/bin/cp.exe\" tools/zig/cp.zig";
        if (system(compile_cp) != 0) {
            std.debug.print("Error: Failed to compile cp.zig using zig\n", .{});
            std.process.exit(1);
        }
    }

    if (!file_exists(".cargo/config.toml")) {
        const GENERIC_WRITE: u32 = 0x40000000;
        const CREATE_ALWAYS: u32 = 2;
        const FILE_ATTRIBUTE_NORMAL: u32 = 0x80;

        const h = CreateFileA(".cargo/config.toml", GENERIC_WRITE, 0, null, CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, null);
        if (h != null and @intFromPtr(h.?) != 0xFFFFFFFFFFFFFFFF) {
            const content =
                "# Auto-generated by Axiom Zig Toolchain (build.zig)\n" ++
                "# Enables standalone zero-dependency building without MSYS64 or Visual Studio\n\n" ++
                "[target.x86_64-pc-windows-gnu]\n" ++
                "linker = \"rust-lld\"\n" ++
                "ar = \"ar.exe\"\n\n" ++
                "[env]\n" ++
                "CC = \"gcc.exe\"\n" ++
                "CXX = \"g++.exe\"\n" ++
                "AR = \"ar.exe\"\n";
            var written: u32 = 0;
            _ = WriteFile(h, content.ptr, @intCast(content.len), &written, null);
            _ = CloseHandle(h);
        }
    }

    std.debug.print("==> Zig toolchain ready at .tools/bin and configured in .cargo/config.toml\n", .{});
}

fn configure_path() void {
    if (builtin.os.tag == .windows) {
        var cwd_buf: [4096:0]u8 = undefined;
        _ = GetCurrentDirectoryA(@intCast(cwd_buf.len), &cwd_buf);
        var cur_path: [32768:0]u8 = undefined;
        _ = GetEnvironmentVariableA("PATH", &cur_path, @intCast(cur_path.len));

        var new_path: [32768:0]u8 = undefined;
        const cwd_span = std.mem.span(@as([*:0]u8, @ptrCast(&cwd_buf)));
        const path_span = std.mem.span(@as([*:0]u8, @ptrCast(&cur_path)));

        var pos: usize = 0;
        @memcpy(new_path[pos .. pos + cwd_span.len], cwd_span);
        pos += cwd_span.len;

        const tools_suffix = "\\.tools\\bin;";
        @memcpy(new_path[pos .. pos + tools_suffix.len], tools_suffix);
        pos += tools_suffix.len;

        @memcpy(new_path[pos .. pos + path_span.len], path_span);
        pos += path_span.len;

        new_path[pos] = 0;

        _ = SetEnvironmentVariableA("PATH", &new_path);
    }
}

pub fn main() u8 {
    const argc = @as(usize, @intCast(__p___argc().*));
    const argv = __p___argv().*;

    if (argc > 1 and argv[1] != null and std.mem.eql(u8, std.mem.span(argv[1].?), "setup")) {
        ensure_setup();
        return 0;
    }

    const exe_ext = if (builtin.os.tag == .windows) ".exe" else "";
    if (!file_exists(".tools/bin/gcc" ++ exe_ext)) {
        ensure_setup();
    }

    configure_path();

    if (argc == 1) {
        const ret = system("cargo build --release");
        return if (ret == 0) 0 else 1;
    }

    var cmd_buf: [32768:0]u8 = undefined;
    var pos: usize = 0;

    const cargo_prefix = "cargo";
    @memcpy(cmd_buf[pos .. pos + cargo_prefix.len], cargo_prefix);
    pos += cargo_prefix.len;

    var start_idx: usize = 1;
    if (argv[1] != null and std.mem.eql(u8, std.mem.span(argv[1].?), "cargo")) {
        start_idx = 2;
    }

    var i = start_idx;
    while (i < argc) : (i += 1) {
        if (argv[i]) |arg| {
            cmd_buf[pos] = ' ';
            pos += 1;
            const arg_span = std.mem.span(arg);
            @memcpy(cmd_buf[pos .. pos + arg_span.len], arg_span);
            pos += arg_span.len;
        }
    }
    cmd_buf[pos] = 0;

    const ret = system(&cmd_buf);
    return if (ret == 0) 0 else 1;
}
