/*
 * Axiom Zero-Bloat Toolchain Runner
 * Cross-platform C implementation (Windows, Linux, macOS)
 * Eliminates PowerShell/Bash dependencies by managing Zig toolchain shims
 * and PATH configuration natively before executing Cargo/NPM.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#ifdef _WIN32
#include <direct.h>
#include <windows.h>
#define mkdir_compat(dir) _mkdir(dir)
#define EXE_EXT ".exe"
#else
#include <sys/stat.h>
#include <unistd.h>
#define mkdir_compat(dir) mkdir(dir, 0755)
#define EXE_EXT ""
#endif

static void ensure_setup(void) {
    mkdir_compat(".tools");
    mkdir_compat(".tools/bin");
    mkdir_compat(".cargo");

    // 1. Compile toolchain_shim.c -> .tools/bin/gcc
    printf("==> Compiling native Zig toolchain shims...\n");
    int ret = system("zig cc -O2 -s -o .tools/bin/gcc" EXE_EXT " tools/zig/toolchain_shim.c");
    if (ret != 0) {
        fprintf(stderr, "Error: Failed to compile toolchain_shim.c using zig cc\n");
        exit(1);
    }

    // 2. Duplicate shims for g++, ar, dlltool, clang, clang++
    const char* tools[] = { "g++", "ar", "dlltool", "clang", "clang++", NULL };
    for (int i = 0; tools[i] != NULL; i++) {
        char dest[256];
        snprintf(dest, sizeof(dest), ".tools/bin/%s%s", tools[i], EXE_EXT);
#ifdef _WIN32
        CopyFileA(".tools/bin/gcc.exe", dest, FALSE);
#else
        char cmd[512];
        snprintf(cmd, sizeof(cmd), "cp -f .tools/bin/gcc .tools/bin/%s", tools[i]);
        system(cmd);
#endif
    }

    // 3. Compile cp.c on Windows
#ifdef _WIN32
    ret = system("zig cc -O2 -s -o .tools/bin/cp.exe tools/zig/cp.c");
    if (ret != 0) {
        fprintf(stderr, "Error: Failed to compile cp.c using zig cc\n");
        exit(1);
    }
#endif

    // 4. Ensure .cargo/config.toml exists
    FILE* f = fopen(".cargo/config.toml", "r");
    if (!f) {
        FILE* out = fopen(".cargo/config.toml", "w");
        if (out) {
            fprintf(out,
                "# Auto-generated by Axiom Zig Toolchain (build.zig)\n"
                "# Enables standalone zero-dependency building without MSYS64 or Visual Studio\n\n"
                "[target.x86_64-pc-windows-gnu]\n"
                "linker = \"rust-lld\"\n"
                "ar = \"ar.exe\"\n\n"
                "[env]\n"
                "CC = \"gcc.exe\"\n"
                "CXX = \"g++.exe\"\n"
                "AR = \"ar.exe\"\n"
            );
            fclose(out);
        }
    } else {
        fclose(f);
    }

    printf("==> Zig toolchain ready at .tools/bin and configured in .cargo/config.toml\n");
}

static void configure_path(void) {
#ifdef _WIN32
    char cwd[MAX_PATH];
    GetCurrentDirectoryA(MAX_PATH, cwd);
    char current_path[32768];
    GetEnvironmentVariableA("PATH", current_path, sizeof(current_path));
    char new_path[32768];
    snprintf(new_path, sizeof(new_path), "%s\\.tools\\bin;%s", cwd, current_path);
    SetEnvironmentVariableA("PATH", new_path);
#else
    char cwd[1024];
    if (getcwd(cwd, sizeof(cwd)) != NULL) {
        const char* current_path = getenv("PATH");
        char new_path[32768];
        snprintf(new_path, sizeof(new_path), "%s/.tools/bin:%s", cwd, current_path ? current_path : "");
        setenv("PATH", new_path, 1);
    }
#endif
}

int main(int argc, char* argv[]) {
    const char* subcmd = (argc > 1) ? argv[1] : "check";

    if (strcmp(subcmd, "setup") == 0) {
        ensure_setup();
        return 0;
    }

    // Auto-setup if gcc shim does not exist
    FILE* test_file = fopen(".tools/bin/gcc" EXE_EXT, "r");
    if (!test_file) {
        ensure_setup();
    } else {
        fclose(test_file);
    }

    configure_path();

    if (strcmp(subcmd, "check") == 0) {
        return system("cargo check --workspace");
    } else if (strcmp(subcmd, "test") == 0) {
        return system("cargo test --workspace -- --test-threads=1");
    } else if (strcmp(subcmd, "build") == 0) {
        return system("cargo build --release");
    } else if (strcmp(subcmd, "ui") == 0) {
        return system("npm --prefix ui run build");
    } else {
        fprintf(stderr, "Unknown command: %s (supported: setup, check, test, build, ui)\n", subcmd);
        return 1;
    }
}
