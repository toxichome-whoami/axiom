# Axiom Zig Toolchain Setup Script
$ErrorActionPreference = "Stop"

$repoRoot = (Resolve-Path "$PSScriptRoot/../..").Path
$toolsBin = Join-Path $repoRoot ".tools/bin"
$shimSource = Join-Path $repoRoot "tools/zig/toolchain_shim.c"

if (!(Test-Path $toolsBin)) {
    New-Item -ItemType Directory -Force -Path $toolsBin | Out-Null
}

Write-Host "==> Compiling native Zig toolchain shims..." -ForegroundColor Cyan
$gccExe = Join-Path $toolsBin "gcc.exe"
& zig cc -O2 -s -o $gccExe $shimSource
if ($LASTEXITCODE -ne 0) {
    Write-Error "Failed to compile toolchain shim using zig cc"
    exit 1
}

# Duplicate shims for required GCC/LLVM utilities
$tools = @("g++.exe", "ar.exe", "dlltool.exe", "clang.exe", "clang++.exe")
foreach ($t in $tools) {
    Copy-Item $gccExe (Join-Path $toolsBin $t) -Force
}

$cpSource = Join-Path $repoRoot "tools/zig/cp.c"
$cpExe = Join-Path $toolsBin "cp.exe"
& zig cc -O2 -s -o $cpExe $cpSource

# Ensure .cargo/config.toml exists and points to .tools/bin
$cargoDir = Join-Path $repoRoot ".cargo"
if (!(Test-Path $cargoDir)) {
    New-Item -ItemType Directory -Force -Path $cargoDir | Out-Null
}

$cargoConfig = Join-Path $cargoDir "config.toml"
$configContent = @"
# Auto-generated by Axiom Zig Toolchain (build.zig)
# Enables standalone zero-dependency building without MSYS64 or Visual Studio

[target.x86_64-pc-windows-gnu]
linker = "rust-lld"
ar = "ar.exe"

[env]
CC = "gcc.exe"
CXX = "g++.exe"
AR = "ar.exe"
"@

Set-Content -Path $cargoConfig -Value $configContent -Encoding utf8

Write-Host "==> Zig toolchain ready at .tools/bin and configured in .cargo/config.toml" -ForegroundColor Green
